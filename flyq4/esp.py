"""Crop a subnetwork and export it for the ESP32 port (flyq_blob.{h,c})."""
from pathlib import Path
import ctypes, subprocess
import numpy as np
from . import quant as Q
from .runtime import HERE

def crop_bfs(indptr, indices, data, seeds, n_max, theta):
    """Breadth-first from the stimulus along edges with |w|>=theta; keep first n_max neurons."""
    n = len(indptr) - 1
    seen = np.zeros(n, bool); order = []
    frontier = np.asarray(seeds, dtype=np.int64)
    seen[frontier] = True; order.extend(frontier.tolist())
    while len(order) < n_max and len(frontier):
        nxt = []
        for u in frontier:
            a, b = indptr[u], indptr[u + 1]
            nb = indices[a:b][np.abs(data[a:b]) >= theta]
            nb = nb[~seen[nb]]
            if len(nb):
                seen[nb] = True; nxt.append(nb)
        if not nxt: break
        frontier = np.unique(np.concatenate(nxt))
        order.extend(frontier.tolist())
    keep = np.array(order[:n_max], dtype=np.int64)
    return keep

def induced(indptr, indices, data, keep):
    """Induced subgraph on `keep` (new index = position in keep)."""
    n = len(indptr) - 1
    remap = np.full(n, -1, dtype=np.int64); remap[keep] = np.arange(len(keep))
    rows = np.repeat(np.arange(n), np.diff(indptr))
    m = (remap[rows] >= 0) & (remap[indices] >= 0)
    from scipy.sparse import csr_matrix
    sub = csr_matrix((data[m], (remap[rows[m]], remap[indices[m]])), shape=(len(keep),) * 2, dtype=np.int32)
    sub.sort_indices()
    return sub.indptr.astype(np.uint32), sub.indices.astype(np.uint32), sub.data.astype(np.int32)

def _arr(name, a, ctype, per_line=12):
    body = ",".join(str(int(x)) for x in a)
    return f"const {ctype} {name}[{max(1, len(a))}] = {{{body if len(a) else '0'}}};\n"

def write_blob(out_dir, indptr, indices, t, lut, stim, stim_q16, ref_spikes, ref_ticks):
    out = Path(out_dir); out.mkdir(parents=True, exist_ok=True)
    n, nnz = len(indptr) - 1, len(indices)
    packed = Q.pack_ternary(t)
    (out / "flyq_blob.h").write_text(f"""/* generated by flyq4.esp - do not edit */
#pragma once
#include <stdint.h>
#define FLYQ_N {n}
#define FLYQ_NNZ {nnz}
#define FLYQ_PSP0 {int(lut[0])}
#define FLYQ_PSP1 {int(lut[1])}
#define FLYQ_PSP2 {int(lut[2])}
#define FLYQ_PSP3 {int(lut[3])}
#define FLYQ_V_REST {Q.V_REST_Q16}
#define FLYQ_V_THRESH {Q.V_TH_Q16}
#define FLYQ_ALPHA_M {Q.ALPHA_M_Q16}
#define FLYQ_G_SHIFT {Q.G_SHIFT}
#define FLYQ_REFRAC {Q.REFRAC_T}
#define FLYQ_STIM_N {len(stim)}
#define FLYQ_STIM_Q16 {round(0.55 * 65536)}
#define FLYQ_REF_SPIKES {ref_spikes}
#define FLYQ_REF_TICKS {ref_ticks}
extern const uint32_t flyq_indptr[{n + 1}];
extern const uint16_t flyq_indices[{max(1, nnz)}];
extern const uint8_t  flyq_weights[{max(1, len(packed))}];
extern const uint16_t flyq_stim[{max(1, len(stim))}];
""")
    (out / "flyq_blob.c").write_text('#include "flyq_blob.h"\n' + _arr("flyq_indptr", indptr, "uint32_t")
        + _arr("flyq_indices", indices, "uint16_t") + _arr("flyq_weights", packed, "uint8_t")
        + _arr("flyq_stim", stim, "uint16_t"))
    return dict(n=n, nnz=nnz, weight_bytes=len(packed), index_bytes=2 * nnz, indptr_bytes=4 * (n + 1),
                state_bytes=n * (4 + 4 + 1 + 2) + 4 * n)

def build_port_lib(out_dir="build"):
    """Compile the ESP32 core with the host compiler, for bit-exactness testing."""
    out = Path(out_dir); out.mkdir(parents=True, exist_ok=True)
    src = HERE.parent / "esp32" / "components" / "flyq"
    so = out / "libflyq_esp.so"
    subprocess.run(["gcc", "-O2", "-std=c99", "-Wall", "-Wextra", "-pedantic", "-shared", "-fPIC",
                    f"-I{src/'include'}", str(src / "flyq.c"), "-o", str(so)], check=True)
    return ctypes.CDLL(str(so))

class EspNet(ctypes.Structure):
    _fields_ = [("n", ctypes.c_uint32), ("indptr", ctypes.c_void_p), ("indices", ctypes.c_void_p),
                ("weights", ctypes.c_void_p), ("psp", ctypes.c_int32 * 4),
                ("v_rest", ctypes.c_int32), ("v_thresh", ctypes.c_int32), ("alpha_m", ctypes.c_int32),
                ("g_shift", ctypes.c_uint32), ("refrac_ticks", ctypes.c_uint8),
                ("V", ctypes.c_void_p), ("G", ctypes.c_void_p), ("refrac", ctypes.c_void_p),
                ("queue", ctypes.c_void_p), ("spike_count", ctypes.c_uint32), ("edge_ops", ctypes.c_uint32)]

def run_port(lib, indptr, indices16, packed, lut, stim, ticks, stim_mv=0.55):
    n = len(indptr) - 1
    V = np.full(n, Q.V_REST_Q16, np.int32); G = np.zeros(n, np.int32)
    R = np.zeros(n, np.uint8); queue = np.zeros(n, np.uint16)
    I = np.zeros(n, np.int32); I[stim] = round(stim_mv * 65536)
    counts = np.zeros(ticks, np.uint32)
    net = EspNet(n, indptr.ctypes.data, indices16.ctypes.data, packed.ctypes.data,
                 (ctypes.c_int32 * 4)(*lut), Q.V_REST_Q16, Q.V_TH_Q16, Q.ALPHA_M_Q16, Q.G_SHIFT,
                 Q.REFRAC_T, V.ctypes.data, G.ctypes.data, R.ctypes.data, queue.ctypes.data, 0, 0)
    queue[:len(stim)] = stim; net.spike_count = len(stim)
    lib.flyq_run.restype = ctypes.c_uint32
    lib.flyq_run.argtypes = [ctypes.POINTER(EspNet), ctypes.c_uint32, ctypes.c_void_p, ctypes.c_void_p]
    total = lib.flyq_run(ctypes.byref(net), ticks, I.ctypes.data, counts.ctypes.data)
    return int(total), counts, int(net.edge_ops)
